(function () {
    "use strict";
    var DESCRIPTION_MAX = 300;

    // Show/hide the high-value required-fields block when the checkbox
    // is toggled. Clicking the checkbox itself only - the surrounding
    // text is a <span>, not a <label>, so it never toggles the box.
    var checkbox = document.getElementById("addRequiresSchool");
    var hvBlock = document.getElementById("addHvFields");
    if (checkbox && hvBlock) {
        checkbox.addEventListener("change", function () {
            var on = checkbox.checked;
            hvBlock.style.display = on ? "" : "none";
            hvBlock.setAttribute("aria-hidden", on ? "false" : "true");
        });
    }

    // Description character counter.
    var desc = document.getElementById("addDescription");
    var counter = document.getElementById("addDescCounter");
    if (desc && counter) {
        function update() {
            var len = desc.value.length;
            counter.textContent = len + " / " + DESCRIPTION_MAX;
            counter.classList.toggle("is-near-limit", (DESCRIPTION_MAX - len) <= 30 && (DESCRIPTION_MAX - len) > 0);
            counter.classList.toggle("is-over-limit", len > DESCRIPTION_MAX);
        }
        desc.addEventListener("input", update);
        update();
    }
})();
